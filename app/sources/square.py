"""Binance Square official account source (Binance Wallet).

Access reality (verified in Phase 2):
  * Binance does NOT expose a public API for Square
    (dev.binance.vision: "The Bapi endpoints are not public endpoints...").
  * All /bapi/composite/* calls require browser fingerprint headers generated
    by the front-end axios interceptor (bnc-uuid, csrftoken, device-info,
    x-trace-id...). Plain HTTP calls return `data: null`.
  * The profile page is a JS SPA (no server-side content).
  * robots.txt disallows automated access to the bapi paths.

v1 constraints forbid Chromium/Playwright and third-party API services, so the
default mode is BLOCKED: the adapter stays wired in, logs a clear reason, and
the per-source health status is SOURCE_BLOCKED (never a fake PASS). On a
production box where a one-time captured header set is available, set
SQUARE_MODE=attempt and SQUARE_EXTRA_HEADERS=<json> to try the documented
endpoints. SQUARE_MODE=fixture runs the parser/merge pipeline offline.
"""

import json
import logging
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

from app.models import SourceMessage
from app.sources.base import SourceBlockedError, SourceParseError, SourceProvider

log = logging.getLogger("binance-alpha.square")

BLOCKED_REASON = (
    "Binance Square has no public API: /bapi/composite/* endpoints require "
    "browser fingerprint headers (bnc-uuid/csrftoken/device-info) generated by "
    "the front-end interceptor; plain HTTP returns data:null; robots.txt "
    "disallows automated access; browser automation is out of scope for v1. "
    "Adapter retained; status = SOURCE_BLOCKED."
)

_PROFILE_ENDPOINT = "/bapi/composite/v3/friendly/pgc/user/client"
_POSTS_ENDPOINT = "/bapi/composite/v2/friendly/pgc/content/queryUserProfilePageContentsWithFilter"


def _extract_posts(payload) -> list[dict]:
    """Tolerant extraction of post dicts from a Square envelope.

    Accepts either the full ComposeResponse envelope (code/data) or a bare
    list/object containing posts. A post is a dict carrying at least one of:
    postId / id / content.
    """
    posts: list[dict] = []

    def walk(node):
        if isinstance(node, dict):
            if (("content" in node or "text" in node)
                    and ("postId" in node or "id" in node or "postId" in str(node.keys()))):
                posts.append(node)
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(payload)
    # de-dup by id, keep order
    seen, out = set(), []
    for p in posts:
        pid = p.get("postId") or p.get("id")
        if pid in seen:
            continue
        seen.add(pid)
        out.append(p)
    return out


def parse_square_payload(payload: dict, profile: str,
                         api_base: str = "https://www.binance.com") -> list[SourceMessage]:
    """Convert a Square API envelope into SourceMessage objects."""
    # envelope check: a null data block means the fingerprint headers were
    # missing -> the endpoint is effectively blocked for plain HTTP
    if payload.get("data") is None:
        raise SourceBlockedError(BLOCKED_REASON)
    posts = _extract_posts(payload)
    messages: list[SourceMessage] = []
    for p in posts:
        post_id = str(p.get("postId") or p.get("id") or "").strip()
        content = (p.get("content") or p.get("text") or "").strip()
        if not post_id or not content:
            continue
        ts_ms = p.get("publishTime") or p.get("publishTime") or 0
        published_at = None
        if ts_ms:
            try:
                published_at = datetime.fromtimestamp(int(ts_ms) / 1000.0,
                                                      tz=timezone.utc)
            except (TypeError, ValueError, OSError):
                published_at = None
        url = p.get("url") or p.get("shareUrl") or ""
        if not url:
            url = f"{api_base}/en/square/post/{post_id}"
        messages.append(
            SourceMessage(
                source="binance_square",
                source_message_id=post_id,
                raw_text=content,
                published_at=published_at,
                message_url=url,
            )
        )
    return messages


class BinanceSquareSource(SourceProvider):
    key = "binance_square"
    name = "binance_square"
    official = True
    description = "Binance Wallet official Binance Square account (mode-dependent)"

    def __init__(self, profile: str = "binancewallet",
                 api_base: str = "https://www.binance.com",
                 mode: str = "blocked",
                 fixture_path: str | None = None,
                 extra_headers: dict | None = None,
                 timeout: int = 15, max_retries: int = 1):
        self.profile = profile
        self.api_base = api_base.rstrip("/")
        self.mode = mode
        self.fixture_path = fixture_path
        self.extra_headers = extra_headers or {}
        self.timeout = timeout
        self.max_retries = max_retries

    # ------------------------------------------------------------- transport
    def _request(self, url: str, body: dict | None = None) -> dict:
        headers = {
            "User-Agent": ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                           "AppleWebKit/537.36 (KHTML, like Gecko) "
                           "Chrome/126.0.0.0 Safari/537.36"),
            "Accept": "application/json, text/plain, */*",
            "Content-Type": "application/json",
        }
        headers.update(self.extra_headers)
        data = json.dumps(body).encode("utf-8") if body is not None else None
        req = urllib.request.Request(url, data=data, headers=headers, method="POST" if body is not None else "GET")
        last_exc: Exception | None = None
        for attempt in range(self.max_retries + 1):
            if attempt:
                time.sleep(2 * attempt)
            try:
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    raw = resp.read()
                return json.loads(raw.decode("utf-8", errors="replace"))
            except (urllib.error.URLError, urllib.error.HTTPError,
                    OSError, json.JSONDecodeError) as exc:  # noqa: PERF203
                last_exc = exc
        raise last_exc  # type: ignore[misc]

    # ---------------------------------------------------------------- modes
    def _fetch_attempt(self) -> list[SourceMessage]:
        # 1) resolve the profile handle -> squareUid
        try:
            prof = self._request(
                self.api_base + _PROFILE_ENDPOINT,
                {"encryptedUid": self.profile},
            )
        except Exception as exc:  # noqa: BLE001
            raise SourceBlockedError(
                f"{BLOCKED_REASON} (profile resolve failed: {exc})"
            ) from exc
        square_uid = None
        data = prof.get("data") or {}
        if isinstance(data, dict):
            square_uid = (data.get("squareUid") or data.get("uid")
                          or data.get("userId") or data.get("id"))
        if not square_uid:
            raise SourceBlockedError(
                f"{BLOCKED_REASON} (profile response for @{self.profile} "
                f"returned no squareUid: {json.dumps(prof)[:200]})"
            )
        # 2) fetch the user's posts
        url = (f"{self.api_base}{_POSTS_ENDPOINT}?squareUid={square_uid}"
               f"&pageSize=20&filterType=1")
        payload = self._request(url)
        return parse_square_payload(payload, self.profile, self.api_base)

    def _fetch_fixture(self) -> list[SourceMessage]:
        from pathlib import Path

        payload = json.loads(Path(self.fixture_path).read_text(encoding="utf-8"))
        return parse_square_payload(payload, self.profile, self.api_base)

    def fetch_page(self) -> list[SourceMessage]:
        if self.mode == "fixture":
            return self._fetch_fixture()
        if self.mode == "attempt":
            return self._fetch_attempt()
        # default: blocked
        raise SourceBlockedError(BLOCKED_REASON)
